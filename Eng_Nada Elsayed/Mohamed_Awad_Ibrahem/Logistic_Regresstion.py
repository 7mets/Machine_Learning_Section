def compute_cost(X, y, w, b, *argv):
    m, n = X.shape
    loss_sum = 0
    for i in range(m):
        z = np.dot(w,X[i]) + b
        g = sigmoid(z)
        loss_sum += -y[i] * np.log(g) - ((1 - y[i]) * np.log(1 - g))
    total_cost = loss_sum/m

    return total_cost
def predict(X, w, b):

    m, n = X.shape
    p = np.zeros(m)

    for i in range(m):
        z_wb = 0

        for j in range(n):

            z_wb +=  w[j] * X[i][j]


        z_wb += b


        f_wb = sigmoid(z_wb)

        p[i] = 1 if f_wb >= 0.5 else 0


    return p
